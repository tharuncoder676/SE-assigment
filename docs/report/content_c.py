def section13(doc):
    h1(doc, "13.  Conclusion, Limitations and Possible Improvements")

    h2(doc, "13.1  Conclusion")
    para(doc, "We set out to build a healthcare appointment platform that books a slot exactly "
              "once, keeps slow work off the patient's response, exposes its behaviour as a "
              "documented API and reports its own health. All four hold, and each is backed by "
              "evidence rather than assertion: a ten-thread race producing exactly one "
              "confirmation, structured logs showing the notification written after the response, "
              "a generated OpenAPI document covering every route, and a container built on a "
              "clean runner that answers its own health probe. Twenty-five automated tests cover "
              "95% of the application code and run on every push through a four-stage pipeline "
              "that has already rejected two of our own commits.")
    para(doc, "The single most valuable thing we learned is smaller than the architecture and "
              "more useful: correctness properties belong where they cannot be bypassed. Our "
              "booking code checks whether a slot is taken, but that check is only an "
              "optimisation. The guarantee lives in a `UNIQUE` constraint, because that is the one "
              "place no code path, present or future, can go around.")

