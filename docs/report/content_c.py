def section10(doc):
    h1(doc, "10.  Results and Validation", page_break=True)

    h2(doc, "10.1  How we measured")
    para(doc, "A closed-loop harness runs a pool of worker threads issuing requests continuously "
              "for eight seconds per scenario, recording the latency of every individual request "
              "so that percentiles can be reported rather than a mean that hides the tail. "
              "Connections are pooled, as a browser or gateway would pool them. All figures below "
              "come from one run against the application on a Windows 11 laptop; the raw data is "
              "in the repository as `docs/loadtest-results.json`.")

    note(doc, "**The measurement bug that nearly went into this report.** Our first run reported "
              "2 050 ms for every scenario, at every level of concurrency. A flat number that "
              "does not move when you change the load is not a performance result, it is a "
              "constant, so we went looking for it. On Windows, `localhost` resolves to the IPv6 "
              "address `::1` first, and uvicorn was bound to IPv4 only, so every connection spent "
              "about two seconds failing over. Addressing the server as `127.0.0.1` and reusing "
              "connections gave the real figures — around 1.5 ms. We very nearly published the "
              "wrong ones, and the only reason we did not is that the numbers were too uniform to "
              "believe.")

    h2(doc, "10.2  Throughput and latency")
    figure(doc, FIG / "fig7-performance.png", 16.4,
           "Figure 7 — Measured throughput and latency percentiles against concurrency. Throughput "
           "peaks at 461.7 rps with five workers and then falls as contention grows, which is the "
           "signature of a CPU-bound single process. The p99 at fifty concurrent users is 263 ms, "
           "still comfortably inside the 500 ms budget.")
    table(doc,
          ["Concurrency", "Requests", "Throughput (rps)", "p50 (ms)", "p95 (ms)", "p99 (ms)", "Success"],
          [["1", "2 546", "318.2", "2.98", "3.88", "4.45", "100%"],
           ["5", "3 695", "**461.7**", "9.73", "13.80", "19.91", "100%"],
           ["10", "3 447", "430.2", "20.26", "27.65", "38.15", "100%"],
           ["25", "2 959", "368.7", "50.15", "68.33", "86.94", "100%"],
           ["50", "2 114", "262.3", "101.62", "200.39", "263.21", "100%"]],
          widths=[13, 13, 17, 13, 13, 13, 12], size=8.5,
          align_center=(0, 1, 2, 3, 4, 5, 6))
    para(doc, "Reading this table taught us something we had assumed away. Throughput does not "
              "increase indefinitely with concurrency; it peaks at five workers and then declines "
              "while latency keeps climbing. That is the classic behaviour of a single CPU-bound "
              "process, and it tells us the scaling strategy has to be horizontal — more "
              "replicas behind a load balancer, which the stateless JWT design already permits — "
              "rather than simply pushing more traffic at one instance.")

    figure(doc, FIG / "fig8-endpoint-throughput.png", 16.4,
           "Figure 8 — Throughput by endpoint at 25 concurrent users. The slots endpoint is the "
           "slowest read at 164 rps because it filters and orders a much larger table; it is the "
           "first place we would add an index if traffic grew.")

    h2(doc, "10.3  What security costs")
    figure(doc, FIG / "fig9-crypto-cost.png", 9.4,
           "Figure 9 — Cost of the security primitives, log scale. PBKDF2 verification takes "
           "246 ms; JWT verification takes 0.007 ms — roughly 35 000 times cheaper.")
    para(doc, "This chart is the justification for the whole session design. Deriving a password "
              "hash is expensive **on purpose**: 600 000 rounds is what makes an offline attack on "
              "a stolen database impractical. But if we paid that cost on every request the system "
              "would manage about four requests per second. Verifying a signed token instead costs "
              "seven microseconds. Paying 246 ms once at login and 0.007 ms on every subsequent "
              "request is the trade that makes the system both secure and usable, and it is "
              "visible in Console 4: registration took 674 ms, the authenticated read that "
              "followed took 5.9 ms.")

