    h2(doc, "11.1  Architecture")
    table(doc,
          ["Option", "Advantages", "Limitations", "Verdict"],
          [["Layered monolith",
            "Simplest to build, deploy and reason about; one transaction boundary",
            "Module boundaries erode without discipline; scales only as one unit",
            "Rejected — no seam for later extraction"],
           ["**Modular monolith (chosen)**",
            "Real bounded contexts and one deployable; strong consistency stays free; a service can be extracted later without rewriting callers",
            "Still one scaling unit; a runaway module can affect its neighbours",
            "**Chosen** — the honest fit for four modules and this team"],
           ["Microservices",
            "Independent scaling and deployment; strong fault isolation",
            "Network hops, distributed transactions, four pipelines, far more operational surface",
            "Rejected — costs are real now, benefits arrive at a scale we do not have"],
           ["Serverless functions",
            "Scales to zero; no servers to manage",
            "Cold starts hurt interactive booking; per-invocation database connections are hostile to a relational store",
            "Rejected — wrong shape for a stateful transactional workload"]],
          widths=[16, 30, 32, 22], size=8.2)

    h2(doc, "11.2  Concurrency control — the decision that mattered most")
    table(doc,
          ["Strategy", "Behaviour under a ten-thread race", "Assessment"],
          [["Application-level check only",
            "Multiple threads pass the `is_booked` check before any writes; several bookings are created",
            "Rejected. A check-then-act sequence in application code is a race by construction"],
           ["Optimistic version column",
            "One writer wins, the rest retry; correct, but the retry loop is ours to write and get right",
            "Viable, and preferable at very high write contention"],
           ["**Row lock + UNIQUE constraint (chosen)**",
            "**Exactly one 201, nine 409s, measured in TC-16**",
            "**Chosen.** The database enforces the invariant, so no application path can bypass it"],
           ["Serialisable isolation everywhere",
            "Correct, but serialises unrelated transactions as well",
            "Rejected — a global cost for a local problem"]],
          widths=[20, 43, 37], size=8.3)

    h2(doc, "11.3  Data store and deployment")
    table(doc,
          ["Dimension", "Chosen", "Alternatives considered", "Reasoning"],
          [["Database", "SQLite via SQLAlchemy",
            "PostgreSQL, MySQL, MongoDB",
            "Zero setup for a reviewer, and the ORM keeps the migration to PostgreSQL to a `DATABASE_URL` change. MongoDB was rejected outright: our core invariant is a uniqueness constraint across related rows, which is precisely what a relational engine is for"],
           ["Messaging", "In-process event bus",
            "RabbitMQ, Kafka, Redis Streams",
            "A broker is the right production answer, but it would have added infrastructure we could not host. The interface is broker-shaped, so substitution touches one file"],
           ["Sessions", "Stateless HS256 JWT",
            "Server-side sessions, RS256",
            "Stateless tokens allow horizontal scaling with no shared session store. RS256 becomes worthwhile once several services must verify tokens without sharing a secret"],
           ["Deployment", "Docker image, compose locally",
            "Bare metal, Kubernetes",
            "Containers gave us laptop/CI parity immediately. Kubernetes is the natural next step and the probes we already expose are exactly what it consumes"]],
          widths=[13, 17, 18, 52], size=8.2)

    h2(doc, "11.4  Justification of the final solution")
    para(doc, "The selected solution is a containerised, API-first modular monolith with "
              "event-driven notification, database-enforced booking integrity and a gated CI/CD "
              "pipeline. We chose it because it answers each of the four problems identified in "
              "Section 1.1 with a mechanism rather than an intention: double booking is prevented "
              "by a constraint the application cannot bypass; throughput is protected by moving "
              "slow work off the request path; availability is made observable through probes and "
              "metrics that an orchestrator can act on; and integration is made possible by "
              "publishing a generated contract instead of hiding behaviour behind screens.")
    para(doc, "It is also the solution we can defend on cost. Every component is open source, the "
              "infrastructure bill was zero, and the operational burden is one process and one "
              "database. The main thing we gave up is independent scaling of the four modules, and "
              "the measurements in Section 10 tell us when that will start to matter: throughput "
              "peaks at 462 requests per second per instance, so the first response to growth is "
              "additional replicas, not a rewrite.")


